-- ---------------------------------------------------------------------
-- Nhóm thực đơn
-- ---------------------------------------------------------------------
CREATE TABLE loai_mon (
    ma_loai   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ten_loai  VARCHAR2(50 CHAR)  NOT NULL,
    mo_ta     VARCHAR2(200 CHAR),
    CONSTRAINT pk_loai_mon     PRIMARY KEY (ma_loai),
    CONSTRAINT uq_loai_mon_ten UNIQUE (ten_loai)
);

CREATE TABLE mon (
    ma_mon       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ten_mon      VARCHAR2(100 CHAR) NOT NULL,
    don_vi_tinh  VARCHAR2(20 CHAR)  DEFAULT 'Ly' NOT NULL,
    trang_thai   VARCHAR2(10)       DEFAULT 'CON_BAN' NOT NULL,
    ma_loai      NUMBER             NOT NULL,
    CONSTRAINT pk_mon            PRIMARY KEY (ma_mon),
    CONSTRAINT uq_mon_ten        UNIQUE (ten_mon),
    -- CON_BAN: đặt được; TAM_HET: hiện "Hết hàng", không đặt được; NGUNG_BAN: ẩn khỏi thực đơn
    CONSTRAINT ck_mon_trang_thai CHECK (trang_thai IN ('CON_BAN', 'TAM_HET', 'NGUNG_BAN')),
    CONSTRAINT fk_mon_loai_mon   FOREIGN KEY (ma_loai) REFERENCES loai_mon (ma_loai)
);

-- Giá bán của món theo từng kích cỡ: S = nhỏ, M = vừa, L = lớn, F = một cỡ (món không chia size)
CREATE TABLE mon_size (
    ma_mon   NUMBER      NOT NULL,
    kich_co  VARCHAR2(1) NOT NULL,
    don_gia  NUMBER(10)  NOT NULL,
    CONSTRAINT pk_mon_size         PRIMARY KEY (ma_mon, kich_co),
    CONSTRAINT ck_mon_size_kich_co CHECK (kich_co IN ('S', 'M', 'L', 'F')),
    CONSTRAINT ck_mon_size_don_gia CHECK (don_gia > 0),
    CONSTRAINT fk_mon_size_mon     FOREIGN KEY (ma_mon) REFERENCES mon (ma_mon) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Nhóm nhân sự và tài khoản
-- ---------------------------------------------------------------------
CREATE TABLE chuc_vu (
    ma_cv         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ten_cv        VARCHAR2(50 CHAR) NOT NULL,
    luong_co_ban  NUMBER(12)        NOT NULL,
    CONSTRAINT pk_chuc_vu       PRIMARY KEY (ma_cv),
    CONSTRAINT uq_chuc_vu_ten   UNIQUE (ten_cv),
    CONSTRAINT ck_chuc_vu_luong CHECK (luong_co_ban > 0)
);

CREATE TABLE nhan_vien (
    ma_nv         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ho_ten        VARCHAR2(100 CHAR) NOT NULL,
    ngay_sinh     DATE,
    gioi_tinh     VARCHAR2(3)        NOT NULL,
    sdt           VARCHAR2(15)       NOT NULL,
    dia_chi       VARCHAR2(200 CHAR),
    ngay_vao_lam  DATE               DEFAULT SYSDATE NOT NULL,
    ma_cv         NUMBER             NOT NULL,
    CONSTRAINT pk_nhan_vien           PRIMARY KEY (ma_nv),
    CONSTRAINT uq_nhan_vien_sdt       UNIQUE (sdt),
    CONSTRAINT ck_nhan_vien_gioi_tinh CHECK (gioi_tinh IN ('NAM', 'NU')),
    CONSTRAINT fk_nhan_vien_chuc_vu   FOREIGN KEY (ma_cv) REFERENCES chuc_vu (ma_cv)
);

-- Tài khoản đăng nhập ứng dụng web; mật khẩu lưu dạng băm scrypt, không lưu bản rõ
CREATE TABLE tai_khoan (
    ma_tk          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ten_dang_nhap  VARCHAR2(30)  NOT NULL,
    mat_khau       VARCHAR2(200) NOT NULL,
    vai_tro        VARCHAR2(10)  DEFAULT 'NHAN_VIEN' NOT NULL,
    trang_thai     VARCHAR2(10)  DEFAULT 'HOAT_DONG' NOT NULL,
    ma_nv          NUMBER        NOT NULL,
    CONSTRAINT pk_tai_khoan            PRIMARY KEY (ma_tk),
    CONSTRAINT uq_tai_khoan_ten        UNIQUE (ten_dang_nhap),
    CONSTRAINT uq_tai_khoan_nhan_vien  UNIQUE (ma_nv),
    CONSTRAINT ck_tai_khoan_vai_tro    CHECK (vai_tro IN ('ADMIN', 'NHAN_VIEN')),
    CONSTRAINT ck_tai_khoan_trang_thai CHECK (trang_thai IN ('HOAT_DONG', 'KHOA')),
    CONSTRAINT fk_tai_khoan_nhan_vien  FOREIGN KEY (ma_nv) REFERENCES nhan_vien (ma_nv) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Nhóm bán hàng
-- ---------------------------------------------------------------------
-- Hoá đơn được tạo khi thanh toán (DA_TT); hoá đơn order nhầm chuyển sang DA_HUY
CREATE TABLE hoa_don (
    ma_hd       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ngay_lap    DATE         DEFAULT SYSDATE NOT NULL,
    tong_tien   NUMBER(12)   DEFAULT 0 NOT NULL,
    trang_thai  VARCHAR2(10) DEFAULT 'DA_TT' NOT NULL,
    CONSTRAINT pk_hoa_don            PRIMARY KEY (ma_hd),
    CONSTRAINT ck_hoa_don_tong_tien  CHECK (tong_tien >= 0),
    CONSTRAINT ck_hoa_don_trang_thai CHECK (trang_thai IN ('DA_TT', 'DA_HUY'))
);

CREATE TABLE ct_hoa_don (
    ma_hd     NUMBER      NOT NULL,
    ma_mon    NUMBER      NOT NULL,
    kich_co   VARCHAR2(1) NOT NULL,
    so_luong  NUMBER(5)   NOT NULL,
    don_gia   NUMBER(10)  NOT NULL,   -- giá tại thời điểm bán
    CONSTRAINT pk_ct_hoa_don          PRIMARY KEY (ma_hd, ma_mon, kich_co),
    CONSTRAINT ck_ct_hoa_don_so_luong CHECK (so_luong > 0),
    CONSTRAINT ck_ct_hoa_don_don_gia  CHECK (don_gia > 0),
    CONSTRAINT fk_ct_hoa_don_hoa_don  FOREIGN KEY (ma_hd) REFERENCES hoa_don (ma_hd) ON DELETE CASCADE,
    CONSTRAINT fk_ct_hoa_don_mon_size FOREIGN KEY (ma_mon, kich_co) REFERENCES mon_size (ma_mon, kich_co)
);

-- ---------------------------------------------------------------------
-- Nhóm kho nguyên liệu
-- ---------------------------------------------------------------------
CREATE TABLE nha_cung_cap (
    ma_ncc   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ten_ncc  VARCHAR2(100 CHAR) NOT NULL,
    dia_chi  VARCHAR2(200 CHAR),
    sdt      VARCHAR2(15)       NOT NULL,
    email    VARCHAR2(100),
    CONSTRAINT pk_nha_cung_cap     PRIMARY KEY (ma_ncc),
    CONSTRAINT uq_nha_cung_cap_sdt UNIQUE (sdt)
);

-- Không lưu số lượng tồn: tồn kho được tính trong view v_ton_kho
CREATE TABLE nguyen_lieu (
    ma_nl          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ten_nl         VARCHAR2(100 CHAR) NOT NULL,
    don_vi_tinh    VARCHAR2(20 CHAR)  NOT NULL,
    ton_toi_thieu  NUMBER(12,2)       DEFAULT 0 NOT NULL,
    don_gia_nhap   NUMBER(12)         NOT NULL,   -- giá nhập hiện tại trên 1 đơn vị tính
    CONSTRAINT pk_nguyen_lieu           PRIMARY KEY (ma_nl),
    CONSTRAINT uq_nguyen_lieu_ten       UNIQUE (ten_nl),
    CONSTRAINT ck_nguyen_lieu_toi_thieu CHECK (ton_toi_thieu >= 0),
    CONSTRAINT ck_nguyen_lieu_gia_nhap  CHECK (don_gia_nhap > 0)
);

CREATE TABLE phieu_nhap (
    ma_pn      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ngay_nhap  DATE       DEFAULT SYSDATE NOT NULL,
    tong_tien  NUMBER(14) DEFAULT 0 NOT NULL,
    ma_ncc     NUMBER     NOT NULL,
    ma_nv      NUMBER     NOT NULL,
    CONSTRAINT pk_phieu_nhap              PRIMARY KEY (ma_pn),
    CONSTRAINT ck_phieu_nhap_tong_tien    CHECK (tong_tien >= 0),
    CONSTRAINT fk_phieu_nhap_nha_cung_cap FOREIGN KEY (ma_ncc) REFERENCES nha_cung_cap (ma_ncc),
    CONSTRAINT fk_phieu_nhap_nhan_vien    FOREIGN KEY (ma_nv)  REFERENCES nhan_vien (ma_nv)
);

CREATE TABLE ct_phieu_nhap (
    ma_pn         NUMBER       NOT NULL,
    ma_nl         NUMBER       NOT NULL,
    so_luong      NUMBER(12,2) NOT NULL,
    don_gia_nhap  NUMBER(12)   NOT NULL,
    CONSTRAINT pk_ct_phieu_nhap             PRIMARY KEY (ma_pn, ma_nl),
    CONSTRAINT ck_ct_phieu_nhap_so_luong    CHECK (so_luong > 0),
    CONSTRAINT ck_ct_phieu_nhap_don_gia     CHECK (don_gia_nhap > 0),
    CONSTRAINT fk_ct_phieu_nhap_phieu_nhap  FOREIGN KEY (ma_pn) REFERENCES phieu_nhap (ma_pn) ON DELETE CASCADE,
    CONSTRAINT fk_ct_phieu_nhap_nguyen_lieu FOREIGN KEY (ma_nl) REFERENCES nguyen_lieu (ma_nl)
);

-- Định lượng nguyên liệu cho 1 đơn vị món theo từng kích cỡ (cầu nối giữa bán hàng và kho)
CREATE TABLE cong_thuc (
    ma_mon      NUMBER       NOT NULL,
    kich_co     VARCHAR2(1)  NOT NULL,
    ma_nl       NUMBER       NOT NULL,
    dinh_luong  NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_cong_thuc             PRIMARY KEY (ma_mon, kich_co, ma_nl),
    CONSTRAINT ck_cong_thuc_dinh_luong  CHECK (dinh_luong > 0),
    CONSTRAINT fk_cong_thuc_mon_size    FOREIGN KEY (ma_mon, kich_co) REFERENCES mon_size (ma_mon, kich_co) ON DELETE CASCADE,
    CONSTRAINT fk_cong_thuc_nguyen_lieu FOREIGN KEY (ma_nl) REFERENCES nguyen_lieu (ma_nl)
);

-- ---------------------------------------------------------------------
-- View tồn kho: tồn = tổng nhập - lượng tiêu hao theo công thức của các
-- hoá đơn hợp lệ (DA_TT). Hoá đơn đã huỷ không được tính.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW v_ton_kho AS
SELECT nl.ma_nl,
       nl.ten_nl,
       nl.don_vi_tinh,
       nl.ton_toi_thieu,
       nl.don_gia_nhap,
       NVL(nhap.tong_nhap, 0)                             AS tong_nhap,
       NVL(xuat.tong_tieu_hao, 0)                         AS tong_tieu_hao,
       NVL(nhap.tong_nhap, 0) - NVL(xuat.tong_tieu_hao, 0) AS so_luong_ton
  FROM nguyen_lieu nl
  LEFT JOIN (SELECT ma_nl,
                    SUM(so_luong) AS tong_nhap
               FROM ct_phieu_nhap
              GROUP BY ma_nl) nhap
         ON nhap.ma_nl = nl.ma_nl
  LEFT JOIN (SELECT c.ma_nl,
                    SUM(ct.so_luong * c.dinh_luong) AS tong_tieu_hao
               FROM ct_hoa_don ct
               JOIN hoa_don h   ON h.ma_hd = ct.ma_hd
               JOIN cong_thuc c ON c.ma_mon = ct.ma_mon AND c.kich_co = ct.kich_co
              WHERE h.trang_thai = 'DA_TT'
              GROUP BY c.ma_nl) xuat
         ON xuat.ma_nl = nl.ma_nl;
